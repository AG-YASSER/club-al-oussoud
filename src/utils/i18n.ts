export type SupportedLanguage = 'fr' | 'ar' | 'en';

export function getWhatsAppReminder(
  lang: SupportedLanguage,
  name: string,
  plan: string,
  daysRemaining: number,
  isUnpaid: boolean
): string {
  if (lang === 'ar') {
    if (isUnpaid) {
      return `السلام عليكم أخي ${name}، نود تذكيرك من طرف نادي الأسود (Club Al Oussoud) بخصوص أداء اشتراكك (${plan}). يرجى تسوية المبلغ في الاستقبال. شكراً لك!`;
    }
    if (daysRemaining <= 0) {
      return `السلام عليكم أخي ${name}، نخبرك بأن اشتراكك (${plan}) في نادي الأسود قد انتهت صلاحيته. ننتظر زيارتك لتجديده ومواصلة تمارينك!`;
    }
    return `السلام عليكم أخي ${name}، نخبرك من نادي الأسود بأن اشتراكك (${plan}) سينتهي خلال ${daysRemaining} يوم. تذكر تجديده للاستمرار في التمارين بدون انقطاع!`;
  }

  if (lang === 'en') {
    if (isUnpaid) {
      return `Hello ${name}, friendly reminder from Club Al Oussoud regarding your pending payment for the ${plan} membership. Please settle at the front desk.`;
    }
    if (daysRemaining <= 0) {
      return `Hello ${name}, your ${plan} subscription at Club Al Oussoud has expired. Please renew on your next visit to keep training!`;
    }
    return `Hello ${name}, your ${plan} subscription at Club Al Oussoud will expire in ${daysRemaining} day(s). Remember to renew to continue workouts without interruption!`;
  }

  // Default: French
  if (isUnpaid) {
    return `Bonjour ${name}, rappel amical de Club Al Oussoud concernant votre cotisation en attente pour la formule ${plan}. Merci de régulariser à la réception.`;
  }
  if (daysRemaining <= 0) {
    return `Bonjour ${name}, votre abonnement ${plan} à Club Al Oussoud a expiré. Pensez à le renouveler lors de votre prochaine séance !`;
  }
  return `Bonjour ${name}, votre abonnement ${plan} à Club Al Oussoud expire dans ${daysRemaining} jour(s). Pensez à le renouveler pour continuer vos entraînements sans interruption !`;
}

